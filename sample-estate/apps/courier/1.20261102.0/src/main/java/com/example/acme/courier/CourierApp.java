package com.example.acme.courier;

import com.example.acme.codegen.annotation.Describe;
import com.example.acme.contract.Receipt;
import com.example.acme.contract.Transfer;
import com.example.acme.contract.Wire;
import com.google.common.collect.ImmutableList;
import hue.captains.singapura.tao.ontology.Mutable;
import javafx.application.Application;
import javafx.geometry.Insets;
import javafx.scene.Node;
import javafx.scene.Scene;
import javafx.scene.control.ScrollPane;
import javafx.scene.layout.VBox;
import javafx.stage.Stage;
import tools.jackson.databind.json.JsonMapper;
import tools.jackson.datatype.guava.GuavaModule;

@Describe("Courier carries transfers between Acme apps")
public final class CourierApp extends Application implements Mutable {

    @Override
    public void start(final Stage stage) {
        final Screen screen = new Screen();
        final VBox body = new VBox(4);
        body.setPadding(new Insets(18));
        final JsonMapper json = JsonMapper.builder().addModule(new GuavaModule()).build();
        final CourierAppDescription description = new CourierAppDescription();
        body.getChildren().addAll(
                screen.heading("Courier 1.20261102.0"),
                screen.line(description.text()),
                screen.section("Running with"),
                screen.check("AcmeContract", () -> new Wire().release()),
                screen.check("Generated by", description::generator),
                screen.check("Jackson", () -> JsonMapper.class.getPackage().getImplementationVersion()),
                screen.check("Guava", () -> ImmutableList.class.getPackage().getImplementationVersion()),
                screen.section("Doing"),
                screen.check("Wire", () -> "compiled for version " + Wire.WIRE_VERSION
                        + ", running version " + new Wire().version()),
                screen.check("Batch as JSON", () -> json.writeValueAsString(ImmutableList.of(
                        new Transfer("alice", "bob", 1250), new Transfer("bob", "carol", 300)))),
                screen.check("Receipt as JSON", () -> json.writeValueAsString(new Receipt("alice", "bob", true))));

        body.getChildren().addAll(screen.section("Classpath"), screen.classpath());

        stage.setTitle(System.getProperty("acme.release", "Courier 1.20261102.0"));
        stage.setScene(new Scene(new ScrollPane(body), 680, 760));
        stage.show();
    }
}
