package com.example.acme.codegen.processor;

import com.example.acme.codegen.annotation.Describe;
import hue.captains.singapura.tao.ontology.Mutable;
import javax.annotation.processing.AbstractProcessor;
import javax.annotation.processing.RoundEnvironment;
import javax.lang.model.SourceVersion;
import javax.lang.model.element.Element;
import javax.lang.model.element.TypeElement;
import javax.tools.Diagnostic;
import java.io.IOException;
import java.io.Writer;
import java.util.Set;

/**
 * AcmeCodegen 1.20261009.0: writes {@code <Type>Description} for each {@link Describe}d type.
 * Mutable because javac hands every processor its environment after construction.
 */
public final class DescribeProcessor extends AbstractProcessor implements Mutable {

    @Override
    public Set<String> getSupportedAnnotationTypes() {
        return Set.of(Describe.class.getName());
    }

    @Override
    public SourceVersion getSupportedSourceVersion() {
        return SourceVersion.latestSupported();
    }

    @Override
    public boolean process(final Set<? extends TypeElement> annotations, final RoundEnvironment round) {
        for (final Element element : round.getElementsAnnotatedWith(Describe.class)) {
            final TypeElement type = (TypeElement) element;
            final String pkg = processingEnv.getElementUtils().getPackageOf(type).getQualifiedName().toString();
            final String name = type.getSimpleName() + "Description";
            final String text = type.getAnnotation(Describe.class).value().replace("\\", "\\\\").replace("\"", "\\\"");
            try (Writer out = processingEnv.getFiler().createSourceFile(pkg + "." + name, type).openWriter()) {
                out.write("package " + pkg + ";\n\n"
                        + "/** Generated by AcmeCodegen 1.20261009.0 from @Describe on " + type.getSimpleName() + ". */\n"
                        + "public final class " + name
                        + " implements hue.captains.singapura.tao.ontology.StatelessFunctionalObject {\n\n"
                        + "    public String text() {\n"
                        + "        return \"" + text + "\";\n"
                        + "    }\n\n"
                        + "    public String generator() {\n"
                        + "        return \"AcmeCodegen 1.20261009.0\";\n"
                        + "    }\n"
                        + "}\n");
            } catch (IOException e) {
                processingEnv.getMessager().printMessage(Diagnostic.Kind.ERROR, e.toString(), element);
            }
        }
        return true;
    }
}
